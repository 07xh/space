import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
const f=(p)=>readFile(new URL('../'+p,import.meta.url),'utf8');
const pkg=JSON.parse(await f('package.json'));
assert(pkg.dependencies.astro.startsWith('7.'),'Expected Astro 7');
assert(pkg.dependencies.svelte.startsWith('^5.'),'Expected Svelte 5');
const index=await f('src/pages/index.astro');
assert(index.includes('HomeTicker')&&index.includes('HomeCompass'),'Mature blog building blocks missing');
assert(!index.includes('Gallery')&&!index.includes('ProjectScene'),'Abandoned project-first UI must not be imported');
assert((await readdir(new URL('../src/content/projects/',import.meta.url))).filter(p=>p.endsWith('.md')).length>=8,'Must have real project metadata');
assert((await readdir(new URL('../src/content/posts/',import.meta.url))).filter(p=>p.endsWith('.md')).length>=6,'Must have real articles');
assert((await readdir(new URL('../src/content/dynamic/',import.meta.url))).filter(p=>p.endsWith('.md')).length>=4,'Must have real moments');
assert((await f('THIRD_PARTY_NOTICES.md')).includes('MIT License'),'Missing upstream attribution');
console.log('PASS: blog-first routes, real content, upstream components and license notices verified.');
console.log('Source checks are not a replacement for Astro build or browser verification.');
